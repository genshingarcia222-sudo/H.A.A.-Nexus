// Renders the batch scorecard as Markdown from the QA report, so the table a
// reviewer reads and the numbers the validator measured cannot disagree.
//
//   node tools/knowledge-corpus/kb-scorecard.mjs --batch KB-001
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { validate } from "./kb-validate.mjs";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

function table(title, counts, total) {
  const rows = Object.entries(counts);
  if (rows.length === 0) return `### ${title}\n\nNone.\n`;
  const lines = [`### ${title}`, "", "| Key | Records | Share |", "| --- | ---: | ---: |"];
  for (const [key, count] of rows) lines.push(`| \`${key}\` | ${count} | ${((count / total) * 100).toFixed(1)}% |`);
  return `${lines.join("\n")}\n`;
}

export function render(batch) {
  const report = validate({ batch });
  const card = report.scorecard;
  const total = card.total || 1;

  return `# Batch scorecard — ${batch}

Generated by \`tools/knowledge-corpus/kb-scorecard.mjs\` from the QA report. Every
number here is measured from the record files on disk; none is asserted.

**Schema:** \`${report.schemaId}\`
**Files:** ${report.files.length}
**QA result:** ${card.errorCount === 0 ? "PASS" : "FAIL"} — ${card.errorCount} error(s), ${card.warningCount} warning(s)

## Headline

| Measure | Value |
| --- | ---: |
| TOTAL | ${card.total} |
| DUPLICATES (exact id or prompt) | ${card.duplicates} |
| NEAR DUPLICATES / superficial variants | ${card.nearDuplicates} |
| SCHEMA ERRORS | ${card.schemaErrors} |
| SOURCE VERIFICATION FAILURES | ${card.sourceVerificationFailures} |
| SAFETY FLAGS | ${card.safetyFlagged} |
| PRIVACY FLAGS | ${card.privacyFlagged} |
| CODING VERSION ISSUES | ${card.codingVersionIssues} |
| UNRESOLVED CONTRADICTIONS (deliberate, tagged) | ${card.unresolvedContradictions} |
| HUMAN REVIEW REQUIRED | ${card.humanReviewRequired} |
| SOURCE VERIFIED | ${card.sourceVerified} |
| APPROVED | ${card.approved} |
| REJECTED | ${card.rejected} |
| DEPRECATED / SUPERSEDED | ${card.deprecated} |

\`APPROVED\` is 0 by design. Nothing in this batch was written by a person and
nothing has been reviewed by one, so nothing may carry an approved state. The
${card.unresolvedContradictions} unresolved contradictions are the deliberate
teaching content of the CONTRADICTION variants, tagged so they are never mistaken
for corpus defects.

${table("By difficulty", card.byDifficulty, total)}
${table("By competency (KB-D axes)", card.byCompetency, total)}
${table("By module", card.byModule, total)}
${table("By task type", card.byTaskType, total)}
${table("By record type", card.byRecordType, total)}
${table("By error target", card.byErrorTarget, total)}
${table("By evidence basis", card.byEvidenceBasis, total)}
${table("By content status", card.byContentStatus, total)}
${table("By access class", card.byAccessClass, total)}
${table("By cited source", card.bySource, total)}
## Gaps

- **Competency axes with no records:** ${card.competencyGaps.length ? card.competencyGaps.join(", ") : "none"}
- **Modules with no records:** ${card.moduleGaps.length ? card.moduleGaps.join(", ") : "none"}
- **Task types with no records:** ${card.taskTypeGaps.length ? card.taskTypeGaps.join(", ") : "none"}

## Findings

${
  report.findings.length === 0
    ? "None. The batch passes every structural, policy and heuristic rule the validator implements."
    : report.findings.map((finding) => `- **${finding.severity} ${finding.rule}** \`${finding.recordId}\`${finding.path ? ` (\`${finding.path}\`)` : ""}: ${finding.message}`).join("\n")
}
`;
}

function main(argv) {
  const batchIndex = argv.indexOf("--batch");
  const batch = batchIndex === -1 ? "KB-001" : argv[batchIndex + 1];
  const target = path.join(REPO_ROOT, "knowledge-corpus/qa", `${batch}.scorecard.md`);
  writeFileSync(target, render(batch));
  console.log(`wrote ${path.relative(REPO_ROOT, target)}`);
  return 0;
}

if (process.argv[1] && import.meta.url === `file://${process.argv[1]}`) {
  process.exit(main(process.argv.slice(2)));
}
